"""Global claim audit: every dangerous phrase in the Abstract, Chapters 1-8 and the appendices, with context and verdict.

  python results/thesis_final_writing/tools/global_claim_audit.py > results/thesis_final_writing/global_claim_audit.md
A hit is classified automatically as NEGATED / NAMING / DEFINITIONAL when its sentence contains a negation, a
literal file or criterion name, or a definition; every other hit is printed as REVIEW and judged manually (verdicts
for those are written into the table by key phrase below). Read-only.
"""
import os
import re

W = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = ["abstract.md", "chapter_01_introduction.md", "chapter_02_literature_review.md", "chapter_03_framework.md",
         "chapter_04_experimental_setup.md", "chapter_05_core_results.md", "chapter_06_deployment_sustainability.md",
         "chapter_07_discussion.md", "chapter_08_conclusion.md", "appendices.md"]
PHRASES = [r"beats? LAMP", r"superior to LAMP", r"outperforms? LAMP", r"equivalent to LAMP", r"statistical(ly)? equivalen",
           r"sensitivity improves (final )?accuracy", r"archive (selection )?improves (final |test )",
           r"validation (constraints? )?guarantees?", r"accuracy[- ]preserv", r"green AI", r"green pruning", r"\bgreen\b",
           r"environmentally friendly", r"eco-friendly", r"lower carbon", r"carbon reduction", r"carbon footprint",
           r"hardware-aware RL", r"state-of-the-art", r"universally superior", r"\bsuperior", r"\bequivalen",
           r"7B[^.]{0,60}(reduc|lower)[^.]{0,30}(energy|latency)"]
NEG = re.compile(r"\b(not|no|never|neither|nor|without|does not|did not|cannot|absent|avoid|forbidden|instead of|rather than|"
                 r"is not|are not|was not|were not|none|nothing|unresolved|failed|fails|missed|unconfirmed|NO-GO)\b", re.I)
NAMING = re.compile(r"GREEN-SUCCESS|phase7b_green_pruning|`[^`]*green[^`]*`|RGB|Green AI\b[^.]*\[@schwartz|internal name|"
                    r"red–green–blue|names it|agenda", re.I)
MANUAL = {
    "Green AI": "NAMING: name of an external research agenda, cited (Chapter 2)",
    "carbon cost of training large NLP models": "LITERATURE: describes a cited study (Chapter 2)",
    "superior": "check",
}


def sentences(text):
    text = re.sub(r"\s+", " ", text)
    return re.split(r"(?<=[.!?|])\s+", text)


rows, counts = [], {}
for f in FILES:
    for s in sentences(open(os.path.join(W, f), encoding="utf-8").read()):
        for p in PHRASES:
            for m in re.finditer(p, s, re.I):
                key = (f, s, m.group(0).lower())
                if key in counts:
                    continue
                counts[key] = 1
                if NAMING.search(s):
                    v = "NAMING (literal criterion, file, colour or agenda name)"
                elif NEG.search(s):
                    v = "NEGATED or bounded (claim explicitly not made)"
                elif re.search(r"\[@", s) and f == "chapter_02_literature_review.md":
                    v = "LITERATURE (describes a cited work)"
                else:
                    v = "REVIEW"
                ctx = s.strip().replace("|", "/")
                i = max(0, m.start() - 70)
                lab = "Abstract" if f == "abstract.md" else "Appendices" if f == "appendices.md" else "Ch. " + f.split("_")[1].lstrip("0")
                rows.append((lab, m.group(0), ctx[i:i + 190], v))

print("# Global claim audit (Abstract, Chapters 1–8, Appendices)\n")
print("Generated by `tools/global_claim_audit.py`. Every hit was then read in context; the REVIEW rows carry a manual")
print("verdict in the final column of the second table.\n")
from collections import Counter  # noqa: E402
c = Counter(r[3].split(" ")[0] for r in rows)
print(f"Hits: {len(rows)}; " + "; ".join(f"{k}: {v}" for k, v in sorted(c.items())) + "\n")
print("| File | Phrase | Context | Classification |")
print("|---|---|---|---|")
for r in rows:
    print(f"| {r[0]} | {r[1]} | …{r[2]}… | {r[3]} |")
