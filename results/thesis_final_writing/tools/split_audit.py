"""Split-governance audit across the Abstract, Chapters 1-8 and appendices. Read-only.

  python results/thesis_final_writing/tools/split_audit.py > results/thesis_final_writing/split_governance_audit.md
"""
import os
import re

W = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = ["abstract.md", "chapter_01_introduction.md", "chapter_02_literature_review.md", "chapter_03_framework.md",
         "chapter_04_experimental_setup.md", "chapter_05_core_results.md", "chapter_06_deployment_sustainability.md",
         "chapter_07_discussion.md", "chapter_08_conclusion.md", "appendices.md"]
lab = lambda f: "Abstract" if f.startswith("abstract") else "Appendices" if f.startswith("appendices") else "Ch. " + f.split("_")[1].lstrip("0")  # noqa: E731


def sents(f):
    t = re.sub(r"\s+", " ", open(os.path.join(W, f), encoding="utf-8").read())
    return re.split(r"(?<=[.!?|])\s+", t)


checks = []


def chk(name, ok, detail):
    checks.append((name, "PASS" if ok else "FAIL", detail))


# 1. 3,000/2,000 tied to Phases 3-4; 2,500/2,500 to Phase 5 onward
bad = []
for f in FILES:
    for s in sents(f):
        if re.search(r"3,000 ?/ ?2,000|3,000 and 2,000", s) and re.search(r"Phase[s]? ?(5|6|7)", s) and not re.search(r"Phases? 3[–-]4|Phases 3 and 4|configuration I\b|config(uration)?\.? I\b", s):
            bad.append(f"{lab(f)}: {s[:140]}")
        if re.search(r"2,500 ?/ ?2,500", s) and re.search(r"Phases? 3\b|Phase 4\b", s) and not re.search(r"Phases? 5|from Phase 5|configuration II", s):
            bad.append(f"{lab(f)}: {s[:140]}")
chk("Configuration I (3,000/2,000) only with Phases 3–4; configuration II (2,500/2,500) only from Phase 5", not bad, "; ".join(bad) or "no misattribution")

# 2. Chapter 5 Phase-3/4 sections label configuration I
t5 = open(os.path.join(W, "chapter_05_core_results.md"), encoding="utf-8").read()
sec = re.split(r"(?m)^## ", t5)
p34 = "".join(s for s in sec if re.match(r"5\.[3-7] ", s))
bare = [m.group(0) for m in re.finditer(r"(?<!configuration-I )VAL-(RL|SELECT)(?! \(I\))", p34)]
ctx = [re.sub(r"\s+", " ", p34[max(0, m.start() - 60):m.end() + 20]) for m in re.finditer(r"(?<!configuration-I )VAL-(RL|SELECT)(?! \(I\))", p34)]
chk("Chapter 5 §§5.3–5.7 (Phases 3–4) write VAL-RL (I) / VAL-SELECT (I)", len(bare) == 0, f"{len(bare)} unlabelled: " + " || ".join(ctx) if bare else "all labelled (I)")

# 3. Phase-7A 5.08 pp loss always with VAL-RL in the same sentence
bad = []
for f in FILES:
    for s in sents(f):
        if re.search(r"(?<![\d.])5\.08", s) and "VAL-RL" not in s and not re.search(r"\|", s):
            bad.append(f"{lab(f)}: {s[:160]}")
chk("Phase-7A 5.08 pp loss stated with its split (VAL-RL) in the same sentence", not bad, ("ADVISORY (split implicit, no cross-split comparison in the sentence): " + "; ".join(bad)) if bad else "all occurrences name VAL-RL")
if bad: checks[-1] = (checks[-1][0], "ADVISORY", checks[-1][2])

# 4. Any sentence comparing 7A loss (5.08 / 4.00) with 7B (1.12) names the split(s)
bad = []
for f in FILES:
    for s in sents(f):
        if "1.12" in s and ("5.08" in s or "4.00" in s):
            if not (re.search(r"VAL-SELECT|same split|selection-split|validation-accuracy", s)):
                bad.append(f"{lab(f)}: {s[:160]}")
chk("7A-vs-7B accuracy comparisons name the split (same-split VAL-SELECT −4.00 vs −1.12)", not bad, "; ".join(bad) or "all comparisons name the split")

# 5. test set never described as selection data
bad = []
for f in FILES:
    for s in sents(f):
        if re.search(r"(select(ed|ion)?|chose|chosen|tun(ed|ing)) (on|using|with) the test( set)?|test(-set)? (accuracy )?(was |is )?used (for|to) (select|choose|tune)", s, re.I) and not re.search(r"\b(never|not|no)\b", s, re.I):
            bad.append(f"{lab(f)}: {s[:160]}")
chk("Test set never described as selection or tuning data", not bad, "; ".join(bad) or "no such description")

# 6. Phase 7A primary split VAL-RL; Phase 7B criterion split VAL-SELECT, as stated in Ch. 4 and Ch. 6
t4 = re.sub(r"\s+", " ", open(os.path.join(W, "chapter_04_experimental_setup.md"), encoding="utf-8").read())
t6 = re.sub(r"\s+", " ", open(os.path.join(W, "chapter_06_deployment_sustainability.md"), encoding="utf-8").read())
ok = ("Phase 7A's pre-registered accuracy split is **VAL-RL**; Phase 7B's is **VAL-SELECT**" in t6) and ("II: **primary** accuracy criterion" in t4) and ("held out; **final** accuracy criterion" in t4)
chk("Phase-7A criterion split = VAL-RL; Phase-7B criterion split = VAL-SELECT (Ch. 4 Table 4.2, Ch. 6 §6.1)", ok, "stated in both chapters" if ok else "check wording")

print("# Split-governance audit\n")
print("Generated by `tools/split_audit.py` over the Abstract, Chapters 1–8 and the appendices.\n")
print("| # | Check | Result | Detail |")
print("|---|---|---|---|")
for i, (n, r, d) in enumerate(checks, 1):
    print(f"| {i} | {n} | {r} | {d.replace('|', '/')} |")
